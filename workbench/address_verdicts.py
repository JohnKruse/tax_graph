"""Address-keyed, append-only human verdicts for the review workbench.

The verdict ledger is deliberately separate from graph and citation artifacts.
Those artifacts are regenerated by the pipeline; this file is human history.
Coverage is derived from the current graph projection and the ledger at read time.
"""

from __future__ import annotations

from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import re
from threading import RLock
from typing import Any, Iterable, Mapping


_WRITE_LOCK = RLock()
_HEX64 = re.compile(r"^[a-f0-9]{64}$")
_YEAR_COMPONENT = re.compile(r"^(?:tax_year|year)=(?:19|20)\d{2}$")
_LEADING_YEAR = re.compile(r"^(?:19|20)\d{2}/")
_LEGACY_COLUMN_YEAR = re.compile(r"_(?:19|20)\d{2}$")
_PUNCTUATION = str.maketrans({
    "\u2010": "-",
    "\u2011": "-",
    "\u2012": "-",
    "\u2013": "-",
    "\u2014": "-",
    "\u2015": "-",
    "\u2212": "-",
    "\u2018": "'",
    "\u2019": "'",
    "\u201a": "'",
    "\u201b": "'",
    "\u201c": '"',
    "\u201d": '"',
    "\u201e": '"',
    "\u00a0": " ",
})


def normalize_review_text(value: Any) -> str:
    """Normalize whitespace and common typography without changing words."""
    text = str(value or "")
    text = text.translate(_PUNCTUATION)
    text = " ".join(text.split())
    return text


def normalize_cited_text(value: Any) -> list[str]:
    """Return deterministic normalized citation text in source-list order."""
    if value is None:
        values: list[Any] = []
    elif isinstance(value, str):
        values = [value]
    else:
        values = list(value) if isinstance(value, Iterable) else [value]
    return [normalize_review_text(item) for item in values if normalize_review_text(item)]


def review_content_fingerprint(label: Any, cited_text: Any = None) -> str:
    """Hash the reviewed label and cited text after stable normalization."""
    content = {
        "label": normalize_review_text(label),
        "cited_text": normalize_cited_text(cited_text),
    }
    canonical = json.dumps(content, ensure_ascii=True, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


def verdict_store_path(root: str | Path, year: str | int) -> Path:
    """Return the human-owned JSONL ledger path for one tax year."""
    return Path(root).resolve() / "review_verdicts" / str(year) / "address_verdicts.jsonl"


def append_address_verdict(
    *,
    root: str | Path,
    year: str | int,
    address: str,
    label: str,
    cited_text: Any = None,
    judgement: str = "approved",
    reviewer_id: str,
    reviewed_at: str | None = None,
    verdict_id: str | None = None,
    store_path: str | Path | None = None,
    provenance: Mapping[str, Any] | None = None,
) -> dict[str, Any]:
    """Append one address verdict and refuse duplicate ids or empty identity."""
    address_value = str(address).strip()
    reviewer_value = str(reviewer_id).strip()
    judgement_value = str(judgement).strip()
    if not address_value:
        raise ValueError("address is required")
    if not reviewer_value or reviewer_value.lower() in {"agent", "codex", "worker", "system"}:
        raise ValueError("reviewer_id must identify the human reviewer")
    if not judgement_value:
        raise ValueError("judgement is required")
    reviewed_at_value, reviewed_at_epoch = _normalize_reviewed_at(reviewed_at)
    content = {
        "label": str(label),
        "cited_text": [str(value) for value in normalize_cited_text(cited_text)],
    }
    record: dict[str, Any] = {
        "verdict_id": verdict_id or _make_verdict_id(address_value, reviewed_at_value),
        "tax_year": int(year),
        "address": address_value,
        "content_fingerprint": review_content_fingerprint(label, cited_text),
        "reviewed_content": content,
        "judgement": judgement_value,
        "reviewer_id": reviewer_value,
        "reviewed_at": reviewed_at_value,
        "reviewed_at_epoch": reviewed_at_epoch,
    }
    if provenance:
        record["provenance"] = dict(provenance)
    _validate_record(record)
    path = Path(store_path).resolve() if store_path is not None else verdict_store_path(root, year)
    with _WRITE_LOCK:
        existing = load_address_verdicts(path) if path.is_file() else []
        if any(item["verdict_id"] == record["verdict_id"] for item in existing):
            raise FileExistsError(f"address verdict is append-only and already exists: {record['verdict_id']}")
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open("a", encoding="utf-8", newline="\n") as stream:
            stream.write(json.dumps(record, ensure_ascii=True, sort_keys=True, separators=(",", ":")) + "\n")
    return record


def load_address_verdicts(path: str | Path) -> list[dict[str, Any]]:
    """Load and validate the complete append-only ledger in file order."""
    ledger_path = Path(path)
    if not ledger_path.is_file():
        return []
    records: list[dict[str, Any]] = []
    seen_ids: set[str] = set()
    for line_number, line in enumerate(ledger_path.read_text(encoding="utf-8").splitlines(), start=1):
        if not line.strip():
            continue
        try:
            record = json.loads(line)
        except json.JSONDecodeError as exc:
            raise ValueError(f"invalid address verdict JSON at {ledger_path}:{line_number}") from exc
        if not isinstance(record, dict):
            raise ValueError(f"address verdict must be an object at {ledger_path}:{line_number}")
        _validate_record(record, source=f"{ledger_path}:{line_number}")
        verdict_id = str(record["verdict_id"])
        if verdict_id in seen_ids:
            raise ValueError(f"duplicate address verdict id: {verdict_id}")
        seen_ids.add(verdict_id)
        records.append(record)
    return records


def derive_cell_coverage(
    manifest_or_units: Mapping[str, Any] | Iterable[Mapping[str, Any]],
    history: Iterable[Mapping[str, Any]],
) -> dict[str, Any]:
    """Walk current cells and return unreviewed, approved, or needs-recheck states."""
    units = _units(manifest_or_units)
    latest = _latest_by_address(history)
    results: list[dict[str, Any]] = []
    seen_addresses: set[str] = set()
    for unit in units:
        address = unit_address(unit)
        if not address:
            raise ValueError(f"derived review unit has no canonical address: {unit.get('unit_id', '<unknown>')}")
        if address in seen_addresses:
            raise ValueError(f"duplicate derived review address: {address}")
        seen_addresses.add(address)
        current_fingerprint = unit_fingerprint(unit)
        verdict = latest.get(address)
        if verdict is None:
            result = _state(unit, "unreviewed", current_fingerprint)
        elif str(verdict.get("judgement")) != "approved":
            result = _state(unit, "unreviewed", current_fingerprint, verdict=verdict)
        elif str(verdict.get("content_fingerprint")) == current_fingerprint:
            result = _state(unit, "approved", current_fingerprint, verdict=verdict)
        else:
            result = _state(unit, "needs_recheck", current_fingerprint, verdict=verdict)
            result["approved"] = True
            result["content_changed"] = True
            result["needs_recheck"] = True
        results.append(result)
    counts = {state: sum(item["state"] == state for item in results) for state in ("unreviewed", "approved", "needs_recheck")}
    return {
        "total_cells": len(results),
        "approved": counts["approved"],
        "unreviewed": counts["unreviewed"],
        "needs_recheck": counts["needs_recheck"],
        "states": counts,
        "by_document": _count_by_document(results),
        "cells": results,
    }


def report_blast_radius(
    manifest_or_units: Mapping[str, Any] | Iterable[Mapping[str, Any]],
    history: Iterable[Mapping[str, Any]],
) -> dict[str, Any]:
    """Report approved cells whose current content no longer matches reviewed content."""
    coverage = derive_cell_coverage(manifest_or_units, history)
    invalidated = [
        {
            "address": item["address"],
            "unit_id": item["unit_id"],
            "verdict_id": item.get("verdict_id"),
            "reviewer_id": item.get("reviewer_id"),
            "previous_fingerprint": item.get("reviewed_fingerprint"),
            "current_fingerprint": item["content_fingerprint"],
            "reason": "reviewed content no longer matches current graph content",
        }
        for item in coverage["cells"]
        if item["state"] == "needs_recheck"
    ]
    approved_total = coverage["approved"] + coverage["needs_recheck"]
    return {
        "approved_total": approved_total,
        "invalidated": len(invalidated),
        "unchanged_approvals": coverage["approved"],
        "items": invalidated,
    }


def rollover_candidates(
    previous_units: Mapping[str, Any] | Iterable[Mapping[str, Any]],
    previous_history: Iterable[Mapping[str, Any]],
    current_units: Mapping[str, Any] | Iterable[Mapping[str, Any]],
    *,
    previous_year: str | int,
) -> list[dict[str, Any]]:
    """Find explicit cross-year approval candidates without silently copying them."""
    prior_by_address = _latest_by_address(previous_history)
    current_by_stable = {
        address_without_year(unit_address(unit)): unit
        for unit in _units(current_units)
        if unit_address(unit)
    }
    candidates: list[dict[str, Any]] = []
    for old_address, verdict in sorted(prior_by_address.items()):
        if str(verdict.get("judgement")) != "approved":
            continue
        stable = address_without_year(old_address)
        unit = current_by_stable.get(stable)
        if unit is None:
            continue
        current_fingerprint = unit_fingerprint(unit)
        if current_fingerprint != str(verdict.get("content_fingerprint")):
            continue
        candidates.append({
            "address": unit_address(unit),
            "unit_id": str(unit.get("unit_id", "")),
            "state": "carried",
            "content_fingerprint": current_fingerprint,
            "source_year": int(previous_year),
            "source_address": old_address,
            "source_verdict_id": str(verdict["verdict_id"]),
            "reviewer_id": str(verdict["reviewer_id"]),
            "reviewed_at": str(verdict["reviewed_at"]),
            "provenance": f"carried from TY{int(previous_year)}; text identical; per-cell confirmation required",
        })
    return candidates


def address_without_year(address: str) -> str:
    """Remove the year component from a canonical address for rollover matching."""
    value = _LEADING_YEAR.sub("", str(address).strip("/"))
    components: list[str] = []
    for component in value.split("/"):
        if _YEAR_COMPONENT.fullmatch(component):
            continue
        key, separator, component_value = component.partition("=")
        if separator and key == "column":
            component = key + separator + _LEGACY_COLUMN_YEAR.sub("", component_value)
        components.append(component)
    return "/".join(components)


def unit_address(unit: Mapping[str, Any]) -> str:
    """Return the canonical address used as verdict identity for one unit."""
    explicit = str(unit.get("address_id") or unit.get("node_id") or "").strip()
    if explicit:
        return explicit
    for ref in unit.get("object_refs", []) or []:
        if isinstance(ref, Mapping) and str(ref.get("object_type")) in {"address", "node"}:
            value = str(ref.get("object_id") or "").strip()
            if value:
                return value
    return ""


def unit_fingerprint(unit: Mapping[str, Any]) -> str:
    """Compute or retrieve the current content fingerprint for one unit."""
    existing = str(unit.get("content_fingerprint") or "")
    if _HEX64.fullmatch(existing):
        return existing
    content = unit.get("review_content")
    if isinstance(content, Mapping):
        return review_content_fingerprint(content.get("label", unit.get("display_name", "")), content.get("cited_text", []))
    cited: list[str] = []
    for citation in unit.get("citations", []) or []:
        if isinstance(citation, Mapping) and citation.get("quoted_text"):
            cited.append(str(citation["quoted_text"]))
    return review_content_fingerprint(unit.get("display_name", ""), cited)


def load_authored_review_context(root: str | Path, year: str | int) -> dict[str, Any]:
    """Load the small committed carryover record for non-derivable authored prose."""
    path = Path(root).resolve() / "review_context" / str(year) / "authored_reviews.yaml"
    if not path.is_file():
        return {"tax_year": int(year), "entries": []}
    import yaml

    payload = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    if not isinstance(payload, dict) or int(payload.get("tax_year", year)) != int(year):
        raise ValueError(f"invalid authored review context: {path}")
    entries = payload.get("entries")
    if not isinstance(entries, list):
        raise ValueError(f"authored review context entries must be a list: {path}")
    return payload


def _validate_record(record: Mapping[str, Any], *, source: str = "address verdict") -> None:
    required = (
        "verdict_id", "tax_year", "address", "content_fingerprint", "reviewed_content",
        "judgement", "reviewer_id", "reviewed_at", "reviewed_at_epoch",
    )
    missing = [key for key in required if record.get(key) in (None, "")]
    if missing:
        raise ValueError(f"{source} missing fields: {', '.join(missing)}")
    if not _HEX64.fullmatch(str(record["content_fingerprint"])):
        raise ValueError(f"{source} has invalid content_fingerprint")
    reviewed_content = record.get("reviewed_content")
    if not isinstance(reviewed_content, Mapping):
        raise ValueError(f"{source} reviewed_content is required")
    if "label" not in reviewed_content or "cited_text" not in reviewed_content:
        raise ValueError(f"{source} reviewed_content must contain label and cited_text")
    if not isinstance(reviewed_content.get("label"), str) or not isinstance(reviewed_content.get("cited_text"), list):
        raise ValueError(f"{source} reviewed_content has invalid shape")
    actual = review_content_fingerprint(reviewed_content.get("label", ""), reviewed_content.get("cited_text", []))
    if actual != record["content_fingerprint"]:
        raise ValueError(f"{source} content_fingerprint does not match reviewed_content")
    try:
        reviewed_at, reviewed_at_epoch = _normalize_reviewed_at(str(record["reviewed_at"]))
    except ValueError as exc:
        raise ValueError(f"{source} has invalid reviewed_at: {exc}") from exc
    if reviewed_at != str(record["reviewed_at"]):
        raise ValueError(f"{source} reviewed_at must be normalized UTC ISO-8601")
    if isinstance(record["reviewed_at_epoch"], bool) or not isinstance(record["reviewed_at_epoch"], int):
        raise ValueError(f"{source} reviewed_at_epoch must be an integer")
    if int(record["reviewed_at_epoch"]) != reviewed_at_epoch:
        raise ValueError(f"{source} reviewed_at and reviewed_at_epoch disagree")


def _latest_by_address(history: Iterable[Mapping[str, Any]]) -> dict[str, dict[str, Any]]:
    latest: dict[str, dict[str, Any]] = {}
    for index, item in enumerate(history):
        record = dict(item)
        _validate_record(record)
        address = str(record["address"])
        previous = latest.get(address)
        if previous is None or (
            int(record["reviewed_at_epoch"]), index
        ) >= (
            int(previous["reviewed_at_epoch"]), int(previous.get("_order", -1))
        ):
            record["_order"] = index
            latest[address] = record
    for record in latest.values():
        record.pop("_order", None)
    return latest


def _units(value: Mapping[str, Any] | Iterable[Mapping[str, Any]]) -> list[Mapping[str, Any]]:
    if isinstance(value, Mapping):
        return [unit for entry in value.get("entries", []) or [] for unit in entry.get("units", []) or [] if isinstance(unit, Mapping)]
    return [unit for unit in value if isinstance(unit, Mapping)]


def _state(
    unit: Mapping[str, Any],
    state: str,
    current_fingerprint: str,
    *,
    verdict: Mapping[str, Any] | None = None,
) -> dict[str, Any]:
    result: dict[str, Any] = {
        "unit_id": str(unit.get("unit_id", "")),
        "address": unit_address(unit),
        "state": state,
        "status": state,
        "approved": state == "approved",
        "content_changed": state == "needs_recheck",
        "needs_recheck": state == "needs_recheck",
        "content_fingerprint": current_fingerprint,
    }
    if unit.get("base_address_id"):
        result["base_address"] = str(unit["base_address_id"])
    if verdict is not None:
        result.update({
            "verdict_id": str(verdict.get("verdict_id", "")),
            "reviewer_id": str(verdict.get("reviewer_id", "")),
            "judgement": str(verdict.get("judgement", "")),
            "reviewed_at": str(verdict.get("reviewed_at", "")),
            "reviewed_fingerprint": str(verdict.get("content_fingerprint", "")),
        })
    return result


def _count_by_document(results: Iterable[Mapping[str, Any]]) -> dict[str, dict[str, int]]:
    counts: dict[str, dict[str, int]] = {}
    for item in results:
        address = str(item.get("address", ""))
        document = next((part.split("=", 1)[1] for part in address.split("/") if part.startswith("document=")), "unlocated")
        state = str(item.get("state", "unreviewed"))
        counts.setdefault(document, {"total": 0, "unreviewed": 0, "approved": 0, "needs_recheck": 0})["total"] += 1
        counts[document][state] = counts[document].get(state, 0) + 1
    return {key: counts[key] for key in sorted(counts)}


def _make_verdict_id(address: str, reviewed_at: str | None) -> str:
    seed = f"{address}|{reviewed_at or _now()}"
    return "verdict_" + hashlib.sha256(seed.encode("utf-8")).hexdigest()[:24]


def _now() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat()


def _normalize_reviewed_at(value: str | None) -> tuple[str, int]:
    """Return UTC ISO-8601 plus truncated whole UTC seconds for ordering."""
    raw = value or _now()
    try:
        parsed = datetime.fromisoformat(str(raw).replace("Z", "+00:00"))
    except ValueError as exc:
        raise ValueError("reviewed_at must be ISO-8601") from exc
    if parsed.tzinfo is None or parsed.utcoffset() is None:
        raise ValueError("reviewed_at must include a timezone")
    epoch = int(parsed.timestamp())
    normalized = datetime.fromtimestamp(epoch, timezone.utc).isoformat()
    return normalized, epoch
